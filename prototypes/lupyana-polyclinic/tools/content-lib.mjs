/**
 * Shared helpers for sync-content.mjs and check-content.mjs, so the check
 * always applies exactly the same transform that the sync does.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
export const root = path.resolve(here, "..");
export const contentPath = path.join(root, "content.json");
export const dataPath = path.join(root, "assets", "js", "content-data.js");
export const LIST_NAMES = ["services", "departments", "facilities", "staff", "photos"];

export const banner = `/* AUTO-GENERATED by tools/sync-content.mjs.
   Edit content.json, then run: npm run sync
   This file exists so the site also works when opened directly from disk. */
`;

export function readContent() {
  return JSON.parse(fs.readFileSync(contentPath, "utf8"));
}

/** Fill missing Swahili strings with [SW: ...] placeholders. Mutates and returns data. */
export function fillSwahili(data) {
  data.sw = data.sw || {};
  for (const [key, value] of Object.entries(data.en || {})) {
    if (!data.sw[key]) data.sw[key] = `[SW: ${value}]`;
  }
  for (const listName of LIST_NAMES) {
    for (const item of data[listName] || []) {
      for (const value of Object.values(item)) {
        if (
          value &&
          typeof value === "object" &&
          !Array.isArray(value) &&
          typeof value.en === "string" &&
          !value.sw
        ) {
          value.sw = `[SW: ${value.en}]`;
        }
      }
    }
  }
  return data;
}

export const serializeContent = (data) => `${JSON.stringify(data, null, 2)}\n`;
export const serializeData = (data) =>
  `${banner}window.__LUPYANA_CONTENT__ = ${JSON.stringify(data, null, 2)};\n`;

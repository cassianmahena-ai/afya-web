/**
 * Sync content.json -> assets/js/content-data.js
 * and fill missing Swahili strings with clearly marked [SW: ...] placeholders.
 *
 * Run after editing content.json:
 *   node tools/sync-content.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const contentPath = path.join(root, "content.json");
const dataPath = path.join(root, "assets", "js", "content-data.js");

const data = JSON.parse(fs.readFileSync(contentPath, "utf8"));

// Fill missing Swahili UI strings. Existing approved translations are never overwritten.
data.sw = data.sw || {};
for (const [key, value] of Object.entries(data.en || {})) {
  if (!data.sw[key]) data.sw[key] = `[SW: ${value}]`;
}

// Fill missing Swahili values in structured lists.
for (const listName of ["services", "departments", "facilities", "staff", "photos"]) {
  for (const item of data[listName] || []) {
    for (const [field, value] of Object.entries(item)) {
      if (
        value &&
        typeof value === "object" &&
        !Array.isArray(value) &&
        typeof value.en === "string" &&
        !value.sw
      ) {
        value.sw = `[SW: ${value.en}]`;
      }
    }
  }
}

fs.writeFileSync(contentPath, `${JSON.stringify(data, null, 2)}\n`, "utf8");

const banner = `/* AUTO-GENERATED by tools/sync-content.mjs.
   Edit content.json, then run: node tools/sync-content.mjs
   This file exists so the site also works when opened directly from disk. */
`;
fs.writeFileSync(
  dataPath,
  `${banner}window.__LUPYANA_CONTENT__ = ${JSON.stringify(data, null, 2)};\n`,
  "utf8"
);

console.log(
  `Synced content.json -> assets/js/content-data.js (${Object.keys(data.en).length} UI strings, ${data.services.length} services).`
);
